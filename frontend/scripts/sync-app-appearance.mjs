// Generate the independent apps' color engine from the same source as MediaHub.
import ts from 'typescript';
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const out = root + 'public/themes/appearance-tokens.js';
const code = ts.transpileModule(readFileSync(root + 'src/appearance-tokens.ts', 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS } }).outputText;
const presets = ts.transpileModule(readFileSync(root + 'src/theme-presets.ts', 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS } }).outputText;
writeFileSync(out, '// Generated by frontend/scripts/sync-app-appearance.mjs. Edit appearance-tokens.ts.\nvar MediaHubAppearance = (() => {\nconst exports = {};\n' + code + '\nconst presetExports = {};\n((exports, require) => {\n' + presets + '\n})(presetExports, () => exports);\nreturn {...exports,...presetExports};\n})();\n');
for (const [app, folder] of [['mediaseed','MediaSeed'], ['mediavpn','MediaVPN']]) {
  const targets = [
    new URL('../../docker/bundled/' + app + '/', import.meta.url),
    new URL('../../../../' + folder + '/', import.meta.url),
  ];
  for (const target of targets) {
    if (!existsSync(target)) continue;
    const themes = new URL(app + '/static/themes/', target);
    copyFileSync(out, new URL('appearance-tokens.js', themes));
    copyFileSync(root + 'src/select-controls.css', new URL('select-controls.css', themes));
    for (const name of ['duck-pond.css','duck-pond.js','duck.svg']) copyFileSync(root + 'public/themes/' + name, new URL(name, themes));
  }
}
const upload = new URL('../../../../MediaUpload/mediaupload/static/', import.meta.url);
if (existsSync(upload)) for (const name of ['appearance-tokens.js','duck-pond.css','duck-pond.js']) {
  copyFileSync(root + 'public/themes/' + name, new URL(name, upload));
}
